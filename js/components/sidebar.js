export function renderSidebar(container, options = {}) {
  const {
    activeTab = 'PDV',
    onSelectTab
  } = options;

  const currentUser = auth.getCurrentUser();
  const userRole = currentUser ? normalizeRole(currentUser.role, currentUser.id) : 'CASHIER';
  const badgeInfo = getRoleBadgeInfo(userRole, currentUser?.id);
  const sections = getNavSectionsForRole(userRole, currentUser?.id);

  let navHtml = '';
  sections.forEach(section => {
    if (!section.items || section.items.length === 0) return;
    navHtml += `
      <div class="sidebar-nav-section">
        <div class="sidebar-section-title">${section.label}</div>
        <nav>
          ${section.items.map(item => {
            const isActive = activeTab === item.id;
            const iconSvg = ICONS[item.icon] || ICONS['package'];
            return `
              <button 
                class="nav-item ${isActive ? 'active' : ''}" 
                data-tab="${item.id}"
                id="nav-item-${item.id.toLowerCase()}"
              >
                <div class="nav-item-content">
                  <span class="nav-item-icon">${iconSvg}</span>
                  <span>${item.label}</span>
                </div>
                ${isActive ? '<svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="m9 18 6-6-6-6"/></svg>' : ''}
              </button>
            `;
          }).join('')}
        </nav>
      </div>
    `;
  });

  container.innerHTML = `
    <aside class="app-sidebar">
      <div style="padding-top: 16px;">
        ${navHtml}
      </div>

      <!-- Footer Role info -->
      <div class="sidebar-footer">
        <div class="sidebar-footer-role">
          <span style="font-size: 9px; font-family: var(--font-mono); color: #94a3b8; text-transform: uppercase;">Perfil Ativo</span>
          <span class="badge ${badgeInfo.badgeClass}" style="font-size: 9px;">${userRole}</span>
        </div>
        <div style="font-weight: 700; color: #f8fafc; margin-top: 4px; white-space: nowrap; overflow: hidden; text-overflow: ellipsis;">
          ${currentUser?.fullName || 'Operador Balcão'}
        </div>
        <div style="font-size: 10px; color: #94a3b8; margin-top: 2px;">
          ${badgeInfo.label}
        </div>
      </div>
    </aside>
  `;

  // Bind clicks
  container.querySelectorAll('[data-tab]').forEach(btn => {
    btn.addEventListener('click', () => {
      const tab = btn.getAttribute('data-tab');
      if (onSelectTab) onSelectTab(tab);
    });
  });
}
